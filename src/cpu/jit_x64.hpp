#pragma once
#include "cpu/execute.hpp"
#include <memory>
#include <span>
#include <vector>
#include <array>
namespace nanorv::cpu {
struct CachedInstruction {
  using Executor=bool(*)(Hart*,const memory::AddressSpace*,const CachedInstruction*,Trap*) noexcept;
  Decoded decoded;u32 original;
};
struct NativeLinkNode {
  static constexpr u64 kSamePageContext=1ull<<63;
  void* block=nullptr;
  const void* entry=nullptr;
  const std::atomic<u64>* generation=nullptr;
  u64 expected_generation=0;
  u32 count=0;
  struct Link {
    u64 pc=0,epoch=0,context=0;NativeLinkNode* target=nullptr;
    const u64* epoch_counter=nullptr;
  };
  std::array<Link,2> next{};
};
struct NativeChain {
  // First member is the resolver ABI used by generated tail-jump exits.
  const void* (*resolve)(NativeChain*,Hart*,const memory::AddressSpace*,Trap*,u32)=nullptr;
  void* state=nullptr;
  // A native self-backedge can check its page and bounded instruction budget
  // without calling the C++ resolver. Updated only by this hart's dispatcher.
  const std::atomic<u64>* generation=nullptr;
  u64 expected_generation=0;
  u32 remaining=0;
  // Per-hart writable descriptors permit guarded jumps between RX blocks.
  // The epoch is checked before any possibly stale target is dereferenced.
  NativeLinkNode* current=nullptr;
  // Virtual entry PC of current. It is updated on every native/slow link so a
  // same-page link can be checked even when a physical block has VA aliases.
  u64 current_pc=0;
  u64 context=0;
  u32 retired=0;
  bool sampling=false;
  bool direct_enabled=true;
  bool inline_loads=true;
  bool inline_stores=true;
  u64 direct_links=0,sampled_instructions=0,sampled_helpers=0;
  const Hart::NativeTranslation* memory_loads=nullptr;
  const Hart::NativeTranslation* memory_stores=nullptr;
  u64 memory_tag=0,sampled_loads=0;
};
// Windows x64 native blocks, always written RW then protected RX (W^X).
class NativeBlock {
public:
  ~NativeBlock();
  static std::unique_ptr<NativeBlock> compile(std::span<const CachedInstruction>);
  static std::vector<std::unique_ptr<NativeBlock>> compile_many(std::span<const std::span<const CachedInstruction>>);
  static CachedInstruction::Executor executor_for(const Decoded&) noexcept;
  u32 run(Hart&, const memory::AddressSpace&, Trap&,NativeChain* chain=nullptr) const;
  const void* entry() const noexcept {return code_;}
  const void* linked_entry() const noexcept {return static_cast<const u8*>(code_)+linked_offset_;}
  // Read-only generated bytes and body bounds for instruction-expansion audits.
  std::span<const u8> code_bytes() const noexcept {return {static_cast<const u8*>(code_),code_size_};}
  std::size_t body_offset() const noexcept {return body_offset_;}
  std::size_t body_size() const noexcept {return body_size_;}
  u64 helper_calls(u32 retired,bool trapped) const noexcept {
    const auto length=helper_prefix_.size()-1;
    if(!length)return 0;
    return (retired/length)*helper_prefix_.back()+helper_prefix_[retired%length]+(trapped?1u:0u);
  }
private:
  struct Prepared;
  struct CodeArena;
  static Prepared prepare(std::span<const CachedInstruction>);
  std::shared_ptr<CodeArena> arena_;
  void* code_ = nullptr;
  std::size_t linked_offset_ = 0;
  std::size_t code_size_ = 0, body_offset_ = 0, body_size_ = 0;
  std::vector<u8> helper_prefix_;
};
}
